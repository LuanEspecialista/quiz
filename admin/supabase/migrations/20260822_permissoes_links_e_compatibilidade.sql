-- Links guardam somente referencias e permissoes. Conteudo protegido e entregue
-- pela RPC abaixo apos validacao; o token armazenado e apenas um hash.
create table if not exists public.links_temporarios (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  titulo text not null,
  publico text not null check (publico in ('cliente','afiliado','investidor')),
  cliente_id_text text,
  afiliado_id uuid references public.afiliados(id) on delete set null,
  empreendimento_ids_text text[] not null default '{}',
  permissoes jsonb not null default '{}'::jsonb,
  senha_hash text,
  expira_em timestamptz not null,
  max_acessos integer check (max_acessos is null or max_acessos > 0),
  acessos integer not null default 0,
  ultimo_acesso_em timestamptz,
  revogado_em timestamptz,
  criado_por uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

